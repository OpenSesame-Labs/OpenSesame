import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { isString } from "../../../scripts/lib/json-boundary.mjs";

const root = fileURLToPath(new URL("../../..", import.meta.url));
const commandSchema = resolve(
  root,
  "packages/app-core/src/browser/saml/post-wire.ts",
);
const generated = resolve(root, "apps/pages/src/sw/saml-command.generated.ts");
const require = createRequire(resolve(root, "packages/app-core/package.json"));
const toolingRequire = createRequire(
  resolve(root, "packages/control-plane/package.json"),
);
const writer = resolve(root, "apps/pages/scripts/write-saml-worker-parser.ts");
const staleMessage =
  "SAML worker parser is stale; run npm exec -w @opensesame/control-plane -- tsx ../../apps/pages/scripts/write-saml-worker-parser.ts and its differential tests.";

/** Changes to the source contract or Zod require regenerating and reviewing the worker parser. */
export function samlWorkerInputs() {
  const source = readFileSync(commandSchema, "utf8").replaceAll("\r\n", "\n");
  const sourceHash = createHash("sha256").update(source).digest("hex");
  const zodVersion = JSON.parse(
    readFileSync(require.resolve("zod/package.json"), "utf8"),
  ).version;
  return { sourceHash, zodVersion };
}

export function checkSamlWorkerFresh(text, expected) {
  const header =
    "// Generated by apps/pages/scripts/generate-saml-worker-parser.mjs; do not edit.\n" +
    `// SAML_SCHEMA_SHA256: ${expected.sourceHash}\n` +
    `// SAML_ZOD_VERSION: ${expected.zodVersion}\n`;
  if (!text.replaceAll("\r\n", "\n").startsWith(header)) {
    throw new Error(staleMessage);
  }
}

export function checkSamlWorkerContents(actual, expected) {
  if (actual.replaceAll("\r\n", "\n") !== expected)
    throw new Error(staleMessage);
}

export function assertSamlWorkerFresh() {
  checkSamlWorkerFresh(readFileSync(generated, "utf8"), samlWorkerInputs());
  const tsxPackage = toolingRequire.resolve("tsx/package.json");
  const tsxBin = JSON.parse(readFileSync(tsxPackage, "utf8")).bin;
  if (!isString(tsxBin)) throw new Error("Unexpected tsx package bin");
  try {
    execFileSync(
      process.execPath,
      [resolve(dirname(tsxPackage), tsxBin), writer, "--check"],
      {
        cwd: root,
        encoding: "utf8",
        timeout: 30000,
      },
    );
  } catch (error) {
    throw new Error(`${staleMessage}\n${error.stderr || error.message}`, {
      cause: error,
    });
  }
}
